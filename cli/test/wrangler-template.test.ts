import { describe, expect, it } from "vitest";
import { parseJsonc, validateConfig } from "../src/config";
import {
  buildWranglerConfig,
  COMPATIBILITY_DATE,
  containerAppNames,
  FORBIDDEN_DO_CONTAINER_FIELDS,
  PROVIDER_CRON,
  renderWranglerJsonc,
} from "../src/wrangler-template";

type Any = Record<string, any>;

describe("wrangler template", () => {
  const cfg = validateConfig({ images: { "registry.example/my:1": "custom" } });
  const w = buildWranglerConfig(cfg, { accountId: "acct123" }) as Any;

  it("declares sqlite exports for OrbSession, Registry and ProviderHost", () => {
    expect(w.exports).toEqual({
      OrbSession: { type: "durable-object", storage: "sqlite" },
      Registry: { type: "durable-object", storage: "sqlite" },
      ProviderHost: { type: "durable-object", storage: "sqlite" },
    });
    expect(w.migrations).toBeUndefined();
  });

  it("passes the provider build as CF_ORBS_PROVIDER_BUILD only when given", () => {
    expect(w.vars.CF_ORBS_PROVIDER_BUILD).toBeUndefined();
    const w2 = buildWranglerConfig(cfg, { providerBuild: "0123456789abcdef" }) as Any;
    expect(w2.vars.CF_ORBS_PROVIDER_BUILD).toBe("0123456789abcdef");
    expect(typeof w2.vars.CF_ORBS_CONFIG).toBe("string");
  });

  it("has two durable_object container entries without forbidden fields", () => {
    expect(w.containers).toHaveLength(2);
    for (const c of w.containers as Any[]) {
      expect(c.scheduling_policy).toBe("durable_object");
      for (const f of FORBIDDEN_DO_CONTAINER_FIELDS) expect(c).not.toHaveProperty(f);
      for (const k of Object.keys(c))
        expect([
          "name",
          "class_name",
          "scheduling_policy",
          "images",
          "observability",
          "ssh",
          "authorized_keys",
          "unsafe",
        ]).toContain(k);
    }
    const [orb, provider] = w.containers as [Any, Any];
    expect(orb.class_name).toBe("OrbSession");
    expect(orb.images.orb).toEqual({ dockerfile: "../image/Dockerfile", build_context: "../image" });
    expect(orb.images.custom).toEqual({
      dockerfile: "../image/custom.Dockerfile",
      build_context: "../image",
    });
    expect(provider.class_name).toBe("ProviderHost");
    expect(provider.images.provider.dockerfile).toBe("provider/Dockerfile");
    for (const img of [...Object.values(orb.images), ...Object.values(provider.images)] as Any[]) {
      expect(Object.keys(img).every((k) => ["dockerfile", "build_context"].includes(k))).toBe(true);
    }
  });

  it("has the cron, config var, bindings, name and pins", () => {
    expect(w.triggers.crons).toEqual([PROVIDER_CRON]);
    expect(JSON.parse(w.vars.CF_ORBS_CONFIG).instance).toEqual(cfg.instance);
    expect(JSON.parse(w.vars.CF_ORBS_CONFIG).images).toEqual(cfg.images);
    expect(w.name).toBe("cf-orbs");
    expect(w.main).toBe("worker/src/index.ts");
    expect(w.compatibility_date).toBe(COMPATIBILITY_DATE);
    expect(w.account_id).toBe("acct123");
    expect(w.durable_objects.bindings.map((b: Any) => b.class_name).sort()).toEqual([
      "OrbSession",
      "ProviderHost",
      "Registry",
    ]);
  });

  it("adds ssh only when debugSsh is on, and never puts secrets in vars", () => {
    expect((w.containers as [Any])[0].ssh).toBeUndefined();
    const w2 = buildWranglerConfig(validateConfig({ debugSsh: true })) as Any;
    expect(w2.containers[0].ssh).toEqual({ enabled: true });
    expect(Object.keys(w.vars)).toEqual(["CF_ORBS_CONFIG"]);
    expect(w.vars.CF_ORBS_CONFIG).not.toMatch(/TOKEN|aop_live_/);
  });

  it("renders valid JSONC with a do-not-edit header", () => {
    const text = renderWranglerJsonc(cfg);
    expect(text.startsWith("// Generated by cf-orbs")).toBe(true);
    expect(parseJsonc(text, "wrangler.jsonc")).toEqual(buildWranglerConfig(cfg));
  });

  it("derives container app names from the worker name", () => {
    expect(containerAppNames("cf-orbs")).toEqual(["cf-orbs-orbsession", "cf-orbs-providerhost"]);
  });
});
